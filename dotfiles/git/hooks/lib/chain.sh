#!/usr/bin/env bash
# Shared helper: also run the repository's own hook, and Git LFS's.
# Sourced by every global hook. Installed by ns-bootstrap.
#
# A global core.hooksPath means git runs only these hooks, never a
# repository's own .git/hooks, so a company repo's commit-msg (a Gerrit
# Change-Id, say) or Git LFS's pre-push would silently stop. With
#   git config ns-bootstrap.chainRepoHooks true
# (the work profile sets it) each global hook runs the repository's hook of
# the same name afterwards, and LFS's own hook where the repository uses LFS.
# Off, nothing here runs.

# _with_input INPUT CMD...: CMD reads INPUT when there is any, else git's stdin.
_with_input() {
    local input="$1"
    shift
    if [ -n "$input" ]; then printf '%s\n' "$input" | "$@"; else "$@"; fi
}

# chain_repo_hook NAME [ARGS...]: a hook that reads stdin (pre-push,
# post-rewrite) gets the same lines in each place it runs.
chain_repo_hook() {
    local name="$1" here dir hook input=""
    shift
    [ "$(git config --bool ns-bootstrap.chainRepoHooks 2>/dev/null)" = true ] || return 0
    case "$name" in pre-push|post-rewrite) input="$(cat)" ;; esac

    here="$(cd "$(dirname "$0")" && pwd -P)"
    dir="$(git rev-parse --git-common-dir 2>/dev/null)/hooks"
    hook="${dir}/${name}"
    if [ -x "$hook" ] && [ "$(cd "$dir" 2>/dev/null && pwd -P)" != "$here" ]; then
        # The global pre-commit hook already runs the pre-commit framework.
        if [ "$name" = pre-commit ] && [ -f .pre-commit-config.yaml ] \
           && grep -q 'File generated by pre-commit' "$hook" 2>/dev/null; then
            :
        else
            _with_input "$input" "$hook" "$@" || return $?
            # A hook that git lfs install wrote already ran LFS.
            grep -q 'git lfs\|git-lfs' "$hook" 2>/dev/null && return 0
        fi
    fi
    chain_lfs "$name" "$input" "$@"
}

# Git LFS's hooks, for a repository that has LFS objects.
chain_lfs() {              # NAME INPUT [ARGS...]
    local name="$1" input="$2"
    shift 2
    case "$name" in pre-push|post-checkout|post-commit|post-merge) ;; *) return 0 ;; esac
    command -v git-lfs >/dev/null 2>&1 || return 0
    [ -d "$(git rev-parse --git-common-dir 2>/dev/null)/lfs" ] || return 0
    _with_input "$input" git lfs "$name" "$@"
}
